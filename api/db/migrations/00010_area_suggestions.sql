-- Area / Thana suggestions at checkout. The buyer may still type anything
-- (free text, like "Mirpur 10"); these names only help them find theirs.
-- Kept in the database (not in the React code) so the Owner can later add
-- names or turn one off (is_active) without a new release.
--
-- district     = a delivery_areas district name, spelled exactly the same.
-- city_area_id = NULL: the name belongs to the whole district.
--                Set: only for that delivery area (Dhaka city / Outside
--                Dhaka city), so the list follows the card the buyer picked.
--
-- Data (docs/data-sources.md):
--   upazilas      nuhil/bangladesh-geocode, commit 5622f68 (2023-03-17), MIT.
--                 Four district names renamed to ours: Barisal -> Barishal,
--                 Chapainawabganj -> Chapai Nawabganj, Coxsbazar -> Cox's
--                 Bazar, Jhalakathi -> Jhalokati. Upazila names unchanged.
--   Dhaka city    the 50 thanas in Wikipedia "Dhaka Metropolitan Police",
--                 revision 1378840650, CC BY-SA 4.0. Names unchanged.
-- TestAreaSuggestionsMatchDistricts checks every district has names and
-- every name points at a real district.
--
-- Never edit this file after it has been applied.

-- +goose Up
CREATE TABLE area_suggestions (
    id           BIGINT  GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    district     TEXT    NOT NULL,
    name         TEXT    NOT NULL CHECK (btrim(name) <> ''),
    city_area_id BIGINT  REFERENCES delivery_areas (id),
    is_active    BOOLEAN NOT NULL DEFAULT true,
    UNIQUE NULLS NOT DISTINCT (district, city_area_id, name)
);

CREATE INDEX area_suggestions_city_area_id_idx ON area_suggestions (city_area_id);

